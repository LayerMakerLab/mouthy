@Test func usageCountsClaudeOncePerMessageAndCodexWithoutCacheReads() throws {
    let now = Date()
    let iso = ISO8601DateFormatter()
    iso.formatOptions = [.withInternetDateTime, .withFractionalSeconds]
    let folder = FileManager.default.temporaryDirectory.appendingPathComponent("mouthy-usage-\(UUID().uuidString)")
    try FileManager.default.createDirectory(at: folder, withIntermediateDirectories: true)
    defer { try? FileManager.default.removeItem(at: folder) }
    let recent = iso.string(from: now.addingTimeInterval(-3600)), old = iso.string(from: now.addingTimeInterval(-6 * 86400))
    let claude = """
    {"type":"assistant","requestId":"r1","timestamp":"\(recent)","message":{"id":"m1","content":"secret words","usage":{"input_tokens":10,"output_tokens":90,"cache_creation_input_tokens":100,"cache_read_input_tokens":5000}}}
    {"type":"assistant","requestId":"r1","timestamp":"\(recent)","message":{"id":"m1","usage":{"input_tokens":10,"output_tokens":90,"cache_creation_input_tokens":100,"cache_read_input_tokens":5000}}}
    {"type":"assistant","requestId":"r2","timestamp":"\(old)","message":{"id":"m2","usage":{"input_tokens":1,"output_tokens":1}}}
    {"type":"user","message":{"content":"no usage here"}}
    """
    let file = folder.appendingPathComponent("a.jsonl")
    try claude.write(to: file, atomically: true, encoding: .utf8)
    var samples: [UsageScanner.Sample] = []
    var seen = Set<String>()
    UsageScanner.forEachLine(file, containing: "\"usage\"") { object in
        guard let message = object["message"] as? [String: Any], let usage = message["usage"] as? [String: Any],
              let date = UsageScanner.parseDate(object["timestamp"]),
              seen.insert((message["id"] as? String ?? "") + (object["requestId"] as? String ?? "")).inserted else { return }
        samples.append(.init(date: date, tokens: ["input_tokens", "output_tokens", "cache_creation_input_tokens"].reduce(0) { $0 + ((usage[$1] as? Int) ?? 0) }))
    }
    let summary = UsageScanner.summarize("Claude Code", samples, limits: [], now: now)
    #expect(summary.fiveHours == 200 && summary.week == 202)
    #expect(summary.hourly.reduce(0, +) == 200)
    #expect(UsageScanner.recentFiles(under: folder, now: now) == [file].map { $0.resolvingSymlinksInPath() } || UsageScanner.recentFiles(under: folder, now: now).count == 1)
}

