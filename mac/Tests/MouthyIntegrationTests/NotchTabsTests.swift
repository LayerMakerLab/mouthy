/// Counts every HTTP request URLSession.shared tries, and fails it without touching the network.
final class RequestCounter: URLProtocol, @unchecked Sendable {
    nonisolated(unsafe) static var count = 0
    static let lock = NSLock()
    override class func canInit(with request: URLRequest) -> Bool {
        guard request.url?.scheme?.hasPrefix("http") == true else { return false }
        lock.withLock { count += 1 }
        return true
    }
    override class func canonicalRequest(for request: URLRequest) -> URLRequest { request }
    override func startLoading() { client?.urlProtocol(self, didFailWithError: URLError(.notConnectedToInternet)) }
    override func stopLoading() {}
}

@MainActor @Test func localOnlyModeStopsEveryNotchRequest() async {
    let original = MouthyTabs.networkAllowed
    URLProtocol.registerClass(RequestCounter.self)
    defer { MouthyTabs.networkAllowed = original; URLProtocol.unregisterClass(RequestCounter.self) }
    let track = MusicTab.Track(title: "Song", artist: "Artist", album: "", duration: 200, player: "Music")
    let place = WeatherTab.Place(name: "Paris", latitude: 48.9, longitude: 2.3, fahrenheit: true)

    MouthyTabs.networkAllowed = { false }
    RequestCounter.lock.withLock { RequestCounter.count = 0 }
    let art = await ArtworkClient.fetch(track)
    let lyrics = await LyricsClient.fetch(track)
    let forecast = await WeatherTab.forecast(for: place)
    let city = await WeatherTab.geocode("Paris")
    #expect(art == nil && lyrics.synced.isEmpty && lyrics.plain == nil && forecast == nil && city == nil)
    #expect(RequestCounter.lock.withLock { RequestCounter.count } == 0)

    // The same calls with the network allowed do try (and fail here), so the check above means something.
    MouthyTabs.networkAllowed = { true }
    _ = await WeatherTab.forecast(for: place)
    #expect(RequestCounter.lock.withLock { RequestCounter.count } > 0)
}

