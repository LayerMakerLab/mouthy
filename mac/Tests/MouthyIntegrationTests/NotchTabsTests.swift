@Test func usageReadsOnlyNewCompleteLines() throws {
    let file = FileManager.default.temporaryDirectory.appendingPathComponent("mouthy-lines-\(UUID().uuidString).jsonl")
    defer { try? FileManager.default.removeItem(at: file) }
    try "{\"usage\":1}\n{\"usage\":2}\n{\"usa".write(to: file, atomically: true, encoding: .utf8)
    var seen: [Int] = []
    let first = UsageScanner.forEachLine(file, containing: "usage") { seen.append($0["usage"] as? Int ?? 0) }
    #expect(seen == [1, 2])
    let handle = try FileHandle(forWritingTo: file); try handle.seekToEnd()
    try handle.write(contentsOf: Data("ge\":3}\n".utf8)); try handle.close()
    let second = UsageScanner.forEachLine(file, from: first, containing: "usage") { seen.append($0["usage"] as? Int ?? 0) }
    #expect(seen == [1, 2, 3] && second > first)
}

/// Lines at and over `longest`: a long line that holds the marker still
/// counts, even with the marker split across two reads; a long line without it is skipped.
@Test func usageKeepsLongLinesThatHoldTheMarker() throws {
    let file = FileManager.default.temporaryDirectory.appendingPathComponent("mouthy-long-\(UUID().uuidString).jsonl")
    defer { try? FileManager.default.removeItem(at: file) }
    let longest = 64
    func padded(_ usage: Int, to length: Int) -> String {
        let head = #"{"usage":\#(usage),"p":""#
        return head + String(repeating: "x", count: length - head.utf8.count - 2) + #""}"#
    }
    let atLimit = padded(1, to: longest), overLimit = padded(2, to: longest + 1)
    let noMarker = #"{"p":""# + String(repeating: "y", count: 20_000) + #""}"#
    // "usage" starts two bytes before the first 32 KB read ends.
    let offset = [atLimit, overLimit, noMarker].reduce(0) { $0 + $1.utf8.count + 1 }
    let split = #"{"p":""# + String(repeating: "z", count: (32 << 10) - 2 - offset - 9) + #"","usage":4}"#
    try [atLimit, overLimit, noMarker, split, #"{"usage":5}"#].map { $0 + "\n" }.joined().write(to: file, atomically: true, encoding: .utf8)
    #expect(atLimit.utf8.count == longest && overLimit.utf8.count == longest + 1)
    var seen: [Int] = []
    let end = UsageScanner.forEachLine(file, containing: "usage", longest: longest) { seen.append($0["usage"] as? Int ?? 0) }
    #expect(seen == [1, 2, 4, 5], "\(seen)")
    #expect(end == (try FileManager.default.attributesOfItem(atPath: file.path)[.size] as? Int))
}

