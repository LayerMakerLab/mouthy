@Test func coolArtGlowsWarm() {
    // Blue album art (hue 0.6) glows mic-glow amber at 0.6 saturation; warm art keeps its hue, a little richer.
    let blue = ambientHSB(hue: 0.6, saturation: 0.8, brightness: 0.4)
    #expect(abs(blue.hue - glowHue) < 0.001 && blue.saturation == 0.6 && blue.brightness >= 0.6)
    let teal = ambientHSB(hue: 0.5, saturation: 0.5, brightness: 0.9)
    #expect(abs(teal.hue - glowHue) < 0.001)
    let violet = ambientHSB(hue: 0.8, saturation: 0.5, brightness: 0.9)
    #expect(abs(violet.hue - glowHue) < 0.001)
    let red = ambientHSB(hue: 0.02, saturation: 0.5, brightness: 0.3)
    #expect(red.hue == 0.02 && abs(red.saturation - 0.6) < 0.001 && red.brightness == 0.55)
    let magenta = ambientHSB(hue: 0.9, saturation: 0.5, brightness: 0.7)
    #expect(magenta.hue == 0.9)
}

